#!/usr/bin/env bash
# PreToolUse hook: refuse edits to the generated Data/Raids.lua.
# Reads the hook JSON on stdin; only the file_path value is inspected.
input=$(cat)
path=$(printf '%s' "$input" \
  | grep -oE '"file_path"[[:space:]]*:[[:space:]]*"([^"\\]|\\.)*"' \
  | head -n 1 \
  | sed -e 's/^"file_path"[[:space:]]*:[[:space:]]*"//' -e 's/"$//' \
  | tr -s '\\/' '/')
case "$path" in
  Data/Raids.lua | */Data/Raids.lua)
    echo "Data/Raids.lua is generated by tools/gen_classic_raids.lua. Edit the generator or Data/Forever.lua instead, then regenerate (see README > Supported raids)." >&2
    exit 2
    ;;
esac
exit 0
