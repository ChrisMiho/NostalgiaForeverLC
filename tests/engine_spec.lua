describe("tiered wishlists", function()
    local epic = function() return Q.EPIC end

    it("selects the top of each tier up to the slot counts", function()
        local wish = { hard = { 1, 2, 3 }, soft = { 10, 11, 12, 13 } }
        local h, s, sh, ss = Engine.SelectFromWishlist(wish, { hardReserves = 1, softReserves = 2 }, epic)
        eq(#h, 1); eq(h[1], 1)
        eq(#s, 2); eq(s[1], 10); eq(s[2], 11)
        eq(#sh, 2); eq(sh[1], 2)
        eq(#ss, 2); eq(ss[1], 12)
    end)

    it("fills more slots when the leader allows more", function()
        local wish = { hard = { 1, 2, 3 }, soft = { 10, 11 } }
        local h, s = Engine.SelectFromWishlist(wish, { hardReserves = 3, softReserves = 5 }, epic)
        eq(#h, 3); eq(#s, 2)
    end)

    it("handles zero slots", function()
        local h, s, sh = Engine.SelectFromWishlist({ hard = { 1 }, soft = { 2 } }, { hardReserves = 0, softReserves = 0 })
        eq(#h, 0); eq(#s, 0); eq(#sh, 1)
    end)

    it("skips restricted items and promotes the next one", function()
        local q = function(id) return id == 1 and Q.LEGENDARY or Q.EPIC end
        local h = Engine.SelectFromWishlist({ hard = { 1, 2 } }, { hardReserves = 1, softReserves = 0 }, q)
        eq(h[1], 2)
    end)

    it("never uses a selected hard pick as a soft pick", function()
        local h, s = Engine.SelectFromWishlist({ hard = { 1 }, soft = { 1, 2 } }, { hardReserves = 1, softReserves = 1 }, epic)
        eq(h[1], 1); eq(s[1], 2)
    end)

    it("allows a doubled soft pick only when enabled", function()
        local wish = { soft = { 5, 5, 6 } }
        local _, s = Engine.SelectFromWishlist(wish, { hardReserves = 0, softReserves = 2 }, epic)
        eq(s[1], 5); eq(s[2], 6)
        local _, s2 = Engine.SelectFromWishlist(wish, { hardReserves = 0, softReserves = 2, allowDoubleSoft = true }, epic)
        eq(s2[1], 5); eq(s2[2], 5)
    end)

    it("describes settings changes", function()
        local d = Engine.DiffSettings({ hardReserves = 1, softReserves = 2 }, { hardReserves = 2, softReserves = 2, allowDoubleSoft = true })
        eq(#d, 2); truthy(d[1]:find("1 %-> 2"))
        eq(#Engine.DiffSettings(Engine.DEFAULT_SETTINGS, Engine.DEFAULT_SETTINGS), 0)
    end)
end)

