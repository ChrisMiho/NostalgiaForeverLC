local Engine = dofile("Core/Engine.lua")
local Q, MODE = Engine.QUALITY, Engine.MODE

describe("reserve limits", function()
    it("allows reserves up to the configured amount", function()
        local s = Engine.NewSession({ hardReserves = 1, softReserves = 2 })
        truthy(s:AddReserve("Alice", 100, "soft", Q.EPIC))
        truthy(s:AddReserve("Alice", 101, "soft", Q.EPIC))
        local ok, err = s:AddReserve("Alice", 102, "soft", Q.EPIC)
        falsy(ok); truthy(err:find("no soft reserves left"))
        truthy(s:AddReserve("Alice", 103, "hard", Q.EPIC))
        falsy(s:AddReserve("Alice", 104, "hard", Q.EPIC))
        local h, so = s:Remaining("Alice")
        eq(h, 0); eq(so, 0)
    end)

    it("supports zero hard reserves", function()
        local s = Engine.NewSession({ hardReserves = 0, softReserves = 1 })
        falsy(s:AddReserve("Alice", 100, "hard", Q.EPIC))
    end)

    it("rejects legendary and higher items", function()
        local s = Engine.NewSession()
        local ok, err = s:AddReserve("Alice", 19019, "soft", Q.LEGENDARY)
        falsy(ok); truthy(err:find("restricted"))
        falsy(s:AddReserve("Alice", 1, "hard", Q.ARTIFACT))
        truthy(s:AddReserve("Alice", 2, "soft", Q.EPIC))
    end)

    it("respects a custom restricted threshold", function()
        local s = Engine.NewSession({ restrictedMinQuality = Q.EPIC })
        falsy(s:AddReserve("Alice", 1, "soft", Q.EPIC))
        truthy(s:AddReserve("Alice", 2, "soft", Q.RARE))
    end)

    it("blocks changes while locked unless forced", function()
        local s = Engine.NewSession()
        s:SetLocked(true)
        falsy(s:AddReserve("Alice", 1, "soft", Q.EPIC))
        truthy(s:AddReserve("Alice", 1, "soft", Q.EPIC, true))
        falsy(s:RemoveReserve("Alice", 1, "soft"))
        s:SetLocked(false)
        truthy(s:RemoveReserve("Alice", 1, "soft"))
    end)

    it("lets several players hard reserve the same item", function()
        local s = Engine.NewSession()
        truthy(s:AddReserve("Alice", 1, "hard", Q.EPIC))
        truthy(s:AddReserve("Bob", 1, "hard", Q.EPIC))
        local hard = s:GetReservers(1)
        eq(#hard, 2)
    end)

    it("still blocks hard reserving the same item twice yourself", function()
        local s = Engine.NewSession({ hardReserves = 2 })
        truthy(s:AddReserve("Alice", 1, "hard", Q.EPIC))
        falsy(s:AddReserve("Alice", 1, "hard", Q.EPIC))
    end)

    it("prevents duplicate soft reserves unless allowed", function()
        local s = Engine.NewSession({ softReserves = 3 })
        truthy(s:AddReserve("Alice", 1, "soft", Q.EPIC))
        falsy(s:AddReserve("Alice", 1, "soft", Q.EPIC))
        s:SetSettings({ allowDoubleSoft = true })
        truthy(s:AddReserve("Alice", 1, "soft", Q.EPIC))
    end)

    it("ReplacePlayer reports rejected entries", function()
        local s = Engine.NewSession({ hardReserves = 1, softReserves = 1 })
        s:AddReserve("Alice", 5, "hard", Q.EPIC)
        local ok, rejected = s:ReplacePlayer("Bob", { 5, 8 }, { 6, 7 }, function() return Q.EPIC end)
        truthy(ok)
        eq(#rejected, 2) -- hard 8 over limit, soft 7 over limit (hard 5 shared with Alice is fine)
        eq(#s:GetReservers(5), 2)
        local _, soft = s:GetReservers(6)
        eq(soft[1], "Bob")
    end)
end)

describe("resolve", function()
    local s = Engine.NewSession({ hardReserves = 1, softReserves = 2 })
    s:AddReserve("Alice", 10, "hard", Q.EPIC)
    s:AddReserve("Bob", 20, "soft", Q.EPIC)
    s:AddReserve("Carl", 20, "soft", Q.EPIC)
    s:AddReserve("Carl", 10, "soft", Q.EPIC)

    it("restricted items have no eligible rollers", function()
        local d = s:Resolve(10, Q.LEGENDARY)
        eq(d.mode, MODE.RESTRICTED); eq(#d.eligible, 0)
    end)

    it("hard reserve beats soft reserve", function()
        local d = s:Resolve(10, Q.EPIC)
        eq(d.mode, MODE.HARD); eq(d.eligible[1], "Alice"); eq(#d.soft, 1)
    end)

    it("soft reserve limits rollers to SR holders", function()
        local d = s:Resolve(20, Q.EPIC)
        eq(d.mode, MODE.SOFT); eq(#d.eligible, 2)
    end)

    it("unreserved items are open", function()
        local d = s:Resolve(30, Q.EPIC)
        eq(d.mode, MODE.OPEN); eq(d.eligible, nil)
    end)
end)

describe("rolls", function()
    local s = Engine.NewSession()
    s:AddReserve("Bob", 20, "soft", Q.EPIC)
    s:AddReserve("Carl", 20, "soft", Q.EPIC)

    it("only accepts eligible 1-100 rolls once", function()
        local r = Engine.NewRoll(s:Resolve(20, Q.EPIC))
        truthy(r:Record("Bob", 50, 1, 100))
        falsy(r:Record("Bob", 99, 1, 100))   -- re-roll
        falsy(r:Record("Dave", 99, 1, 100))  -- not reserved
        falsy(r:Record("Carl", 99, 1, 50))   -- wrong range
        eq(#r:Missing(), 1)
        truthy(r:Record("Carl", 70, 1, 100))
        eq(r:Winner(), "Carl")
        eq(#r.ignored, 3)
    end)

    it("detects ties", function()
        local r = Engine.NewRoll(s:Resolve(20, Q.EPIC))
        r:Record("Bob", 70, 1, 100)
        r:Record("Carl", 70, 1, 100)
        local w, tied = r:Winner()
        eq(w, nil); eq(#tied, 2)
    end)

    it("multiple hard reserves shut out soft reservers; only HR holders roll", function()
        local s3 = Engine.NewSession()
        s3:AddReserve("Alice", 1, "hard", Q.EPIC)
        s3:AddReserve("Bob", 1, "hard", Q.EPIC)
        s3:AddReserve("Carl", 1, "soft", Q.EPIC)
        s3:AddReserve("Dana", 1, "soft", Q.EPIC)
        local d = s3:Resolve(1, Q.EPIC)
        eq(d.mode, MODE.HARD); eq(#d.eligible, 2); eq(#d.soft, 2)
        local r = Engine.NewRoll(d)
        eq(r:Winner(), nil)                    -- two HR holders must roll
        falsy(r:Record("Carl", 100, 1, 100))   -- soft reserver ignored
        falsy(r:Record("Zed", 100, 1, 100))    -- random ignored
        truthy(r:Record("Alice", 40, 1, 100))
        truthy(r:Record("Bob", 60, 1, 100))
        eq(#r:Missing(), 0)
        eq(r:Winner(), "Bob")
    end)

    it("single hard reserver wins without rolling", function()
        local s2 = Engine.NewSession()
        s2:AddReserve("Alice", 1, "hard", Q.EPIC)
        local r = Engine.NewRoll(s2:Resolve(1, Q.EPIC))
        eq(r:Winner(), "Alice")
    end)

    it("open rolls accept anyone", function()
        local r = Engine.NewRoll(s:Resolve(999, Q.EPIC))
        truthy(r:Record("Zed", 3, 1, 100))
    end)

    it("restricted rolls accept nobody", function()
        local r = Engine.NewRoll(s:Resolve(20, Q.LEGENDARY))
        falsy(r:Record("Bob", 3, 1, 100))
    end)

    it("closed rolls ignore late rolls", function()
        local r = Engine.NewRoll(s:Resolve(999, Q.EPIC))
        r:Close()
        falsy(r:Record("Zed", 3, 1, 100))
    end)
end)

