describe("main spec / off spec, bonus and plus-ones", function()
    local function open(extra)
        local d = { mode = MODE.OPEN }
        for k, v in pairs(extra or {}) do d[k] = v end
        return d
    end
    it("off spec only wins when nobody rolled main spec", function()
        local r = Engine.NewRoll(open(), { osMax = Engine.OS_ROLL })
        truthy(r:Record("Os", 99, 1, 99))
        truthy(r:Record("Ms", 3, 1, 100))
        eq(r:Winner(), "Ms")
        local s = r:Standings()
        eq(s[1].tier, 1); eq(s[2].tier, 2); eq(s[2].name, "Os")
        local only = Engine.NewRoll(open(), { osMax = 99 })
        only:Record("Os", 12, 1, 99)
        eq(only:Winner(), "Os")
    end)
    it("ignores /roll 99 when off spec rolls are off or the item is reserved", function()
        local r = Engine.NewRoll(open())
        local ok, why = r:Record("Os", 50, 1, 99)
        falsy(ok); truthy(why:find("wrong range"))
    end)
    it("adds the soft reserve bonus to the roll", function()
        local r = Engine.NewRoll({ mode = MODE.SOFT, eligible = { "A", "B" }, bonus = { B = 20 } })
        r:Record("A", 60, 1, 100); r:Record("B", 45, 1, 100)
        eq(r:Winner(), "B")
        local s = r:Standings()
        eq(s[1].value, 45); eq(s[1].bonus, 20); eq(s[1].total, 65)
        local tie = Engine.NewRoll({ mode = MODE.SOFT, eligible = { "A", "B" }, bonus = { B = 10 } })
        tie:Record("A", 60, 1, 100); tie:Record("B", 50, 1, 100)
        local w, tied = tie:Winner()
        eq(w, nil); eq(#tied, 2)
    end)
    it("plus-ones: fewer items won beats a higher roll", function()
        local r = Engine.NewRoll(open({ plus = { Greedy = 2 } }))
        r:Record("Greedy", 100, 1, 100); r:Record("Fresh", 2, 1, 100)
        eq(r:Winner(), "Fresh")
        eq(r:Standings()[2].plus, 2)
    end)
    it("counts plus-ones from unreserved wins only", function()
        local s = Engine.NewSession()
        s:RecordAward(1, "A", MODE.OPEN, 1); s:RecordAward(2, "A", MODE.OPEN, 2)
        s:RecordAward(3, "A", MODE.SOFT, 3); s:RecordAward(4, "B", "DISENCHANT", 4)
        local p = s:PlusOnes()
        eq(p.A, 2); eq(p.B, nil)
    end)
end)

