describe("ledger sync", function()
    local function sample()
        return {
            uid = "Lead;1000", raidKey = "MC", raidName = "Molten Core", leader = "Lead", guild = "Guildies",
            started = 1000, updated = 1500,
            entries = {
                { dropId = 7, itemID = 16800, boss = "Golemagg, the Incinerator", time = 1100, winner = "Bob",
                  mode = "SOFT", awardedAt = 1200, rolls = { { name = "Bob", value = 55 }, { name = "Ann", value = 12 } } },
                { dropId = 8, itemID = 19019, boss = "Trash / other", time = 1300 },
            },
        }
    end
    it("round-trips a run through its text form", function()
        local text = Engine.EncodeRun(sample())
        falsy(text:find("%^"), "no message separators in the payload")
        local run = Engine.DecodeRun(text)
        eq(run.uid, "Lead;1000"); eq(run.raidKey, "MC"); eq(run.raidName, "Molten Core")
        eq(run.leader, "Lead"); eq(run.guild, "Guildies"); eq(run.started, 1000); eq(run.updated, 1500)
        eq(#run.entries, 2)
        local e = run.entries[1]
        eq(e.dropId, 7); eq(e.itemID, 16800); eq(e.boss, "Golemagg  the Incinerator"); eq(e.winner, "Bob")
        eq(e.mode, "SOFT"); eq(e.awardedAt, 1200); eq(#e.rolls, 2); eq(e.rolls[2].name, "Ann"); eq(e.rolls[2].value, 12)
        eq(run.entries[2].winner, nil); eq(run.entries[2].rolls, nil); eq(run.entries[2].boss, "Trash   other")
    end)
    it("rejects damaged text", function()
        eq(Engine.DecodeRun(""), nil); eq(Engine.DecodeRun("garbage"), nil)
        eq(Engine.DecodeRun("u;1,MC,Molten Core,1,1,L,G~1,notanumber,1,B,,,,"), nil)
        local text = Engine.EncodeRun(sample())
        truthy(Engine.Checksum(text) ~= Engine.Checksum(text:sub(1, -2) .. "X"))
        eq(Engine.Checksum(text), Engine.Checksum(text))
    end)
    it("adds a run that is missing, in date order", function()
        local ledger = {}
        Engine.LedgerRun(ledger, "BWL", "Blackwing Lair", "Me", 5000)
