describe("soft reserve bonus", function()
    local function history()
        local ledger = {}
        for week = 1, 3 do
            local run = Engine.LedgerRun(ledger, "MC", "Molten Core", "L", week * 1000000)
            Engine.LedgerNoteReserves(run, { Ann = { soft = { 500 } }, Bob = { soft = { 500 } } })
            Engine.LedgerDrop(run, week, 500, nil, "Boss", week * 1000000 + 1)
        end
        return ledger
    end
    it("grows with every run reserved without winning, up to the cap", function()
        local ledger = history()
        local now = Engine.LedgerRun(ledger, "MC", "Molten Core", "L", 9000000)
        eq(Engine.SoftBonus(ledger, "MC", "Ann", 500, now, 10, 0), 30)
        eq(Engine.SoftBonus(ledger, "MC", "Ann", 500, now, 10, 20), 20)
        eq(Engine.SoftBonus(ledger, "MC", "Ann", 500, now, 0, 20), 0)
        eq(Engine.SoftBonus(ledger, "MC", "Cat", 500, now, 10, 0), 0)
        eq(Engine.SoftBonus(ledger, "BWL", "Ann", 500, now, 10, 0), 0)
    end)
    it("resets when the player won it or skipped a run", function()
        local ledger = history()
        Engine.LedgerAward(ledger.runs[2], 2, 500, "Ann", "SOFT", 2000002)
        ledger.runs[3].sr.Bob = nil
        local now = Engine.LedgerRun(ledger, "MC", "Molten Core", "L", 9000000)
        eq(Engine.SoftBonus(ledger, "MC", "Ann", 500, now, 10, 0), 10)
        eq(Engine.SoftBonus(ledger, "MC", "Bob", 500, now, 10, 0), 0)
    end)
end)

